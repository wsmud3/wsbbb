	this.inherits(NPC);
	this.set({
	    name: "守门人",
	    desc: "他是武道塔的守门人，一个神神秘秘的老头",
	    gender: 1,
	    age: 67,
	    per: 55,
	    mp: 5000000,
	    max_mp: 5000000,
	    hp: 80000000,
	    max_hp: 80000000,
	    level: 5,
	    pfm_rate: 1,
	    prop: {
	        gjsd: 20000,
	        add_sh_per: 100,
	        diff_sh_per: 270,
	        diff_sh_per2: 100,
	        diff_downside_per: 170,
	        gj: 100000,
	        gj_per: 100,
	        diff_fy_per: 150,
	        distime_per: 80,
	        ds: 150000,
	        ds_per: 100,
	        zj: 150000,
	        zj_per: 100,
	        mz: 150000,
	        mz_per: 100
	    }

	});

	// 武帝之路询问
	this.add_action("ask_wd", "武帝之路", function (me) {
	    if (me.level < 4) {
	        return me.notify("守门人瞥了你一眼，淡淡地说道：你的修为还不够，等你到了武圣境界再来找我吧。");
	    }

	    if (me.level >= 5) {
	        return me.notify("守门人原本佝偻的身子微微挺直，一双浑浊的老眼中精光一闪而逝。\n他平静地与你对视，缓缓说道：五气朝元，帝君之境……你已与我一般，踏入了武帝的门槛。\n守门人顿了顿，目光投向武道塔深处，语气中带着几分沧桑：帝君之上，据传尚有更高的境界。只是老朽所知有限，仅晓得与「四方试炼」有关，至于如何触发……还需帝君自行探寻了。");
	    }

	    // level == 4 (武圣)
	    if (!me.query_temp("wd")) {
	        return me.notify("守门人看了你一眼，摇了摇头说道：你还没得到金古易老先生的引荐，老朽不便多言。");
	    }

	    if (me.query_temp("wd_quest")) {
	        // 已经接过任务：只说五岳尚有灵气未得，不点明地点。
	        // （五处全部吸收后会自动进阶武帝，走上面「已是武帝」的分支，这里不会遇到五处都吸收完的情况）
	        return me.notify("守门人对你说道：五岳之巅，尚有灵气未曾认你为主。再去山中走一遭吧，莫要辜负了金古老先生的引荐。");
	    }

	    // 首次对话，告知武帝之路（只说在五岳，不点明地点与条件）
	    me.set_temp("wd_quest", 1);
	    me.notify("守门人听完你的来意，眼中精光一闪，缓缓说道：\n"
	        + "<hiy>金古老先生果然没有看走眼。武圣之上，确有帝君之境！</hiy>\n"
	        + "守门人负手望向远方群山，良久方道：\n"
	        + "<hiz>天地有五行，五岳各镇其一。山巅灵气积蓄千载，却从不轻易认主。\n"
	        + "你须亲登五岳，引动灵气化出试炼之影，胜过它，方得聚元珠；再以此珠纳气归元，是为「五气朝元」。</hiz>\n"
	        + "守门人捋了捋胡须，语气转沉：\n"
	        + "灵气择人而栖。修为不到，莫说纳气，便是那道影子也唤不出来。五气齐聚之日，帝君之境自然水到渠成——去吧。");
	});